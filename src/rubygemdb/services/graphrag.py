"""Contextual GraphRAG engine for ephemeral gem exploration.

Ingests graph.json artifacts generated by the container indexer, builds ephemeral
txtai vector indices for docstrings, signatures, and decode code examples, and performs
two-stage retrieval (semantic vector search + 1-hop graph neighborhood expansion)
to produce grounded LLM prompt contexts.
"""

import hashlib
import json
import logging
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Set

from rubygemdb.core.config import settings
from rubygemdb.services.container_runner import ContainerRunner
from rubygemdb.services.gem_fetcher import GemFetcher

logger = logging.getLogger("rubygemdb.graphrag")


def compute_gem_set_hash(gems: List[str]) -> str:
    """Generate a deterministic 16-character SHA-256 hash for a set of gems."""
    normalized = sorted(list({g.strip().lower() for g in gems if g.strip()}))
    key = ",".join(normalized).encode("utf-8")
    return hashlib.sha256(key).hexdigest()[:16]


class GraphRAGService:
    """Two-stage GraphRAG retrieval service over containerized gem AST and decode graphs."""

    def __init__(
        self,
        gem_fetcher: Optional[GemFetcher] = None,
        container_runner: Optional[ContainerRunner] = None,
        base_dir: Optional[Path] = None,
        embeddings: Optional[Any] = None,
    ):
        self.gem_fetcher = gem_fetcher or GemFetcher()
        self.container_runner = container_runner or ContainerRunner()
        self.base_dir = base_dir or settings.graphrag_dir
        self.base_dir.mkdir(parents=True, exist_ok=True)
        self._embeddings = embeddings

        # In-memory graph structures
        self.active_gems: List[str] = []
        self.active_hash: Optional[str] = None
        self.graph_data: Dict[str, Any] = {"version": "1.0", "gems": [], "nodes": [], "edges": []}
        self.nodes_by_id: Dict[str, Dict[str, Any]] = {}
        self.edges_by_source: Dict[str, List[Dict[str, Any]]] = {}
        self.edges_by_target: Dict[str, List[Dict[str, Any]]] = {}

    def _get_or_create_embeddings(self, index_dir: Path) -> Any:
        """Instantiate txtai embeddings for the given index directory."""
        if self._embeddings is not None:
            return self._embeddings

        from txtai import Embeddings  # type: ignore

        embeddings = Embeddings(
            path="ollama/embeddinggemma",
            backend="sqlite",
            content=True,
            gpu=settings.txtai_gpu,
        )
        return embeddings

    def build_or_load_index(
        self,
        gems: List[str],
        force_rebuild: bool = False,
        progress_callback: Optional[Callable[[str], None]] = None,
    ) -> Dict[str, Any]:
        """Fetch gems, run container extraction if uncached, and populate GraphRAG index."""
        cleaned_gems = sorted(list({g.strip().lower() for g in gems if g.strip()}))
        if not cleaned_gems:
            raise ValueError("Must provide at least one gem name")

        gem_hash = compute_gem_set_hash(cleaned_gems)
        cache_dir = self.base_dir / gem_hash
        graph_file = cache_dir / "graph.json"
        txtai_dir = cache_dir / "txtai"

        self.active_gems = cleaned_gems
        self.active_hash = gem_hash

        # Check if already cached
        if not force_rebuild and graph_file.exists() and txtai_dir.exists():
            msg = f"Loading cached GraphRAG index for [{', '.join(cleaned_gems)}] (hash {gem_hash})..."
            logger.info(msg)
            if progress_callback:
                progress_callback(msg)

            with open(graph_file, "r", encoding="utf-8") as f:
                self.graph_data = json.load(f)

            self._index_graph_memory()
            embeddings = self._get_or_create_embeddings(txtai_dir)
            if hasattr(embeddings, "load") and (txtai_dir / "embeddings").exists():
                try:
                    embeddings.load(str(txtai_dir))
                except Exception as e:
                    logger.warning("Failed to load existing txtai embeddings: %s", e)
            self._embeddings = embeddings

            if progress_callback:
                progress_callback(
                    f"GraphRAG index ready: {len(self.nodes_by_id)} nodes, {len(self.graph_data.get('edges', []))} edges."
                )
            return self.graph_data

        # 1. Fetch / shallow clone each gem
        cache_dir.mkdir(parents=True, exist_ok=True)
        gem_paths: Dict[str, Path] = {}

        for gem_name in cleaned_gems:
            msg = f"Resolving and caching source for gem '{gem_name}'..."
            logger.info(msg)
            if progress_callback:
                progress_callback(msg)

            gem_path = self.gem_fetcher.fetch_gem(gem_name)
            gem_paths[gem_name] = gem_path

        # 2. Run container extraction
        msg = f"Running container extraction for [{', '.join(cleaned_gems)}]..."
        logger.info(msg)
        if progress_callback:
            progress_callback(msg)

        self.graph_data = self.container_runner.run_indexer(
            gem_paths=gem_paths,
            output_dir=cache_dir,
            force_rebuild=force_rebuild,
            progress_callback=progress_callback,
        )

        self._index_graph_memory()

        # 3. Build ephemeral vector index in txtai
        msg = f"Building txtai semantic vector index for {len(self.nodes_by_id)} symbols and doc tags..."
        logger.info(msg)
        if progress_callback:
            progress_callback(msg)

        self._build_vector_index(txtai_dir)

        if progress_callback:
            progress_callback(
                f"GraphRAG index built: {len(self.nodes_by_id)} nodes, {len(self.graph_data.get('edges', []))} edges."
            )
        return self.graph_data

    def _index_graph_memory(self) -> None:
        """Index nodes and edges into fast in-memory lookup tables."""
        self.nodes_by_id.clear()
        self.edges_by_source.clear()
        self.edges_by_target.clear()

        for node in self.graph_data.get("nodes", []):
            nid = node.get("id")
            if nid:
                self.nodes_by_id[nid] = node

        for edge in self.graph_data.get("edges", []):
            src = edge.get("source")
            tgt = edge.get("target")
            if src:
                self.edges_by_source.setdefault(src, []).append(edge)
            if tgt:
                self.edges_by_target.setdefault(tgt, []).append(edge)

    def _build_vector_index(self, txtai_dir: Path) -> None:
        """Create txtai vector embeddings for indexable nodes."""
        txtai_dir.mkdir(parents=True, exist_ok=True)
        embeddings = self._get_or_create_embeddings(txtai_dir)
        self._embeddings = embeddings

        documents = []
        for nid, node in self.nodes_by_id.items():
            ntype = node.get("type")
            data = node.get("data", {})
            name = node.get("name", "")
            gem = node.get("gem", "")
            qname = data.get("qualified_name", name)

            searchable_text = ""
            if ntype == "method":
                sig = data.get("signature", f"def {name}")
                doc = data.get("docstring", "")
                params = ", ".join(p.get("name", "") for p in data.get("parameters", []))
                searchable_text = f"Ruby Method: {qname} (gem: {gem})\nSignature: {sig}\nParameters: {params}\nDocstring: {doc}"
            elif ntype in ("class", "module"):
                doc = data.get("docstring", "") or " ".join(data.get("comments", []))
                super_cls = data.get("superclass", "")
                super_info = f" inherits from {super_cls}" if super_cls else ""
                searchable_text = f"Ruby {ntype.title()}: {qname}{super_info} (gem: {gem})\nDocstring: {doc}"
            elif ntype == "example":
                code = data.get("code", "")
                target = data.get("target", "")
                searchable_text = f"Ruby Code Example for {target} (gem: {gem}):\n{code}"
            elif ntype == "doc_tag":
                directive = data.get("directive", "")
                dtype = data.get("type", "")
                desc = data.get("text", "")
                target = data.get("target", "")
                searchable_text = f"Documentation {directive} for {target} (gem: {gem}): {name} [{dtype}] {desc}"
            else:
                continue

            documents.append({
                "id": nid,
                "text": searchable_text,
                "type": ntype,
                "gem": gem,
                "node_id": nid,
            })

        if documents and hasattr(embeddings, "index"):
            embeddings.index(documents)
            if hasattr(embeddings, "save"):
                try:
                    embeddings.save(str(txtai_dir))
                except Exception as e:
                    logger.debug("txtai embeddings.save notice: %s", e)

    def retrieve(
        self,
        query: str,
        top_k: int = 5,
        expand_hops: int = 1,
    ) -> Dict[str, Any]:
        """Two-stage GraphRAG retrieval: semantic vector search + 1-hop graph neighborhood."""
        if not self.nodes_by_id:
            return {"primary_nodes": [], "expanded_nodes": [], "edges": []}

        primary_node_ids: List[str] = []

        # Stage 1: Vector search
        if self._embeddings is not None and hasattr(self._embeddings, "search"):
            try:
                hits = self._embeddings.search(query, top_k * 2)
                for h in hits:
                    if isinstance(h, (tuple, list)) and len(h) >= 1:
                        nid = str(h[0])
                    elif isinstance(h, dict):
                        nid = str(h.get("id") or h.get("node_id"))
                    else:
                        continue
                    if nid in self.nodes_by_id and nid not in primary_node_ids:
                        primary_node_ids.append(nid)
                    if len(primary_node_ids) >= top_k:
                        break
            except Exception as e:
                logger.warning("Vector search fallback to keyword scan: %s", e)

        # Fallback keyword scan if vector search returns no results or is unavailable
        if not primary_node_ids:
            query_terms = [t.lower() for t in query.split() if len(t) > 2]
            scored = []
            for nid, node in self.nodes_by_id.items():
                text_blob = f"{node.get('name', '')} {json.dumps(node.get('data', {}))}".lower()
                score = sum(1 for term in query_terms if term in text_blob)
                if score > 0:
                    scored.append((score, nid))
            scored.sort(reverse=True)
            primary_node_ids = [nid for _, nid in scored[:top_k]]

        # If still empty, take top symbol nodes
        if not primary_node_ids:
            primary_node_ids = list(self.nodes_by_id.keys())[:top_k]

        # Stage 2: 1-hop graph neighborhood expansion
        expanded_node_ids: Set[str] = set()
        matched_edges: List[Dict[str, Any]] = []

        for nid in primary_node_ids:
            # Outbound edges
            for edge in self.edges_by_source.get(nid, []):
                tgt = edge.get("target")
                if tgt and tgt in self.nodes_by_id:
                    expanded_node_ids.add(tgt)
                    matched_edges.append(edge)

            # Inbound edges
            for edge in self.edges_by_target.get(nid, []):
                src = edge.get("source")
                if src and src in self.nodes_by_id:
                    expanded_node_ids.add(src)
                    matched_edges.append(edge)

        # Remove primary from expanded set to distinguish tiers
        expanded_node_ids.difference_update(primary_node_ids)

        primary_nodes = [self.nodes_by_id[nid] for nid in primary_node_ids if nid in self.nodes_by_id]
        expanded_nodes = [self.nodes_by_id[nid] for nid in sorted(expanded_node_ids) if nid in self.nodes_by_id]

        return {
            "query": query,
            "primary_nodes": primary_nodes,
            "expanded_nodes": expanded_nodes,
            "edges": matched_edges,
        }

    def format_grounded_context(
        self,
        retrieval: Dict[str, Any],
        intention: Optional[str] = None,
    ) -> str:
        """Assemble retrieved AST symbols, parameters, decode tags, and examples into a prompt context."""
        sections: List[str] = []

        if intention and intention.strip():
            sections.append(f"### Project Intention\n{intention.strip()}\n")

        if self.active_gems:
            sections.append(f"### Active Indexed Gems\n{', '.join(self.active_gems)}\n")

        primary_nodes: List[Dict[str, Any]] = retrieval.get("primary_nodes", [])
        expanded_nodes: List[Dict[str, Any]] = retrieval.get("expanded_nodes", [])
        edges: List[Dict[str, Any]] = retrieval.get("edges", [])

        # 1. Signatures & Documentation
        symbols_sec: List[str] = ["### Grounded Ruby API Signatures & Documentation"]
        rendered_symbols = False

        all_nodes = primary_nodes + [n for n in expanded_nodes if n.get("type") in ("method", "class", "module")]
        seen_qnames: Set[str] = set()

        for node in all_nodes:
            ntype = node.get("type")
            data = node.get("data", {})
            name = node.get("name", "")
            qname = data.get("qualified_name", name)
            gem = node.get("gem", "")

            if qname in seen_qnames:
                continue
            seen_qnames.add(qname)

            if ntype == "method":
                rendered_symbols = True
                sig = data.get("signature", f"def {name}")
                doc = data.get("docstring", "")
                symbols_sec.append(f"- **Method `{qname}`** (Gem: `{gem}`)")
                symbols_sec.append(f"  - Signature: `{sig}`")
                if doc:
                    symbols_sec.append(f"  - Summary: {doc}")

                # Find associated doc_tags (parameters, returns) from edges
                nid = node.get("id")
                tag_edges = [
                    e for e in edges if e.get("source") == nid and e.get("type") == "documents"
                ]
                for te in tag_edges:
                    tnode = self.nodes_by_id.get(te.get("target", ""))
                    if tnode and tnode.get("type") == "doc_tag":
                        tdata = tnode.get("data", {})
                        directive = tdata.get("directive", "")
                        if directive == "parameter":
                            pname = tdata.get("name", "")
                            ptype = tdata.get("type", "")
                            pdesc = tdata.get("text", "")
                            type_str = f" [{ptype}]" if ptype else ""
                            desc_str = f" - {pdesc}" if pdesc else ""
                            symbols_sec.append(f"    - `@parameter` `{pname}`{type_str}{desc_str}")
                        elif directive == "returns":
                            rtype = tdata.get("type", "")
                            rdesc = tdata.get("text", "")
                            type_str = f" [{rtype}]" if rtype else ""
                            desc_str = f" - {rdesc}" if pdesc else ""
                            symbols_sec.append(f"    - `@returns`{type_str}{desc_str}")

            elif ntype in ("class", "module"):
                rendered_symbols = True
                doc = data.get("docstring", "") or " ".join(data.get("comments", []))
                super_cls = data.get("superclass")
                super_info = f" < `{super_cls}`" if super_cls else ""
                symbols_sec.append(f"- **{ntype.title()} `{qname}`**{super_info} (Gem: `{gem}`)")
                if doc:
                    symbols_sec.append(f"  - Summary: {doc}")

        if rendered_symbols:
            sections.append("\n".join(symbols_sec) + "\n")

        # 2. Verified Code Examples
        example_nodes = [
            n for n in primary_nodes + expanded_nodes if n.get("type") == "example"
        ]
        if example_nodes:
            ex_sec: List[str] = ["### Verified Code Examples & Usage Snippets"]
            for ex in example_nodes:
                data = ex.get("data", {})
                target = data.get("target", ex.get("name", ""))
                code = data.get("code", "")
                gem = ex.get("gem", "")
                ex_sec.append(f"```ruby\n# Example for {target} (gem: {gem})\n{code}\n```")
            sections.append("\n".join(ex_sec) + "\n")

        return "\n".join(sections)
